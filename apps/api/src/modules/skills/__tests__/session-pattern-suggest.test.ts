/**
 * session:summary → 复发模式 Skill 建议单测（KE-001 P5；#687 依赖倒置自 events 迁入）
 *  - initSessionPatternSuggest 订阅 eventBus 'session:summary'
 *  - patternType 30d 内出现 ≥3 次且无同模式 Skill → 建 proposal 草稿
 *  - unknown 模式 / 不足 3 次 / 已有同模式 Skill → 不建议
 *  - 幂等：重复 init 不重复订阅
 */
import { describe, it, expect, vi, beforeEach } from 'vitest';

const mockReadStudioEventsSince = vi.hoisted(() => vi.fn());
const mockSkillStoreFindFirst = vi.hoisted(() => vi.fn());
const mockSkillStoreCreate = vi.hoisted(() => vi.fn());

vi.mock('../../../utils/studio-events-tail.js', () => ({
  readStudioEventsSince: mockReadStudioEventsSince,
}));

vi.mock('../skill-store.js', () => ({
  skillStore: {
    findFirst: mockSkillStoreFindFirst,
    create: mockSkillStoreCreate,
  },
}));

import { eventBus } from '@dommaker/studio-shared';
import { initSessionPatternSuggest } from '../session-pattern-suggest.js';

const now = Date.now();
const summaryEvent = (patternType: string, ageMs = 0) => ({
  type: 'session:summary',
  source: 'agent-1',
  payload: JSON.stringify({ patternType }),
  createdAt: new Date(now - ageMs).toISOString(),
});

describe('session-pattern-suggest（KE-001 P5 / #687）', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mockSkillStoreFindFirst.mockReturnValue(null);
    mockReadStudioEventsSince.mockResolvedValue([]);
  });

  it('30d 内同模式 ≥3 次且无同模式 Skill → 建 proposal 草稿；重复 init 幂等', async () => {
    mockReadStudioEventsSince.mockResolvedValue([
      summaryEvent('refactor'), summaryEvent('refactor'), summaryEvent('refactor'),
    ]);

    initSessionPatternSuggest();
    initSessionPatternSuggest(); // 幂等：不应重复订阅

    eventBus.publish('session:summary', { patternType: 'refactor', toolsUsed: ['Edit', 'Bash'] });

    await vi.waitFor(() => {
      expect(mockSkillStoreCreate).toHaveBeenCalledTimes(1); // 幂等生效：一次发布仅一次建议
    });
    const arg = mockSkillStoreCreate.mock.calls[0][0];
    expect(arg).toMatchObject({
      companyId: 'system',
      name: 'Pattern: refactor',
      source: 'proposal',
      status: 'draft',
      category: 'refactor',
      tools: JSON.stringify(['Edit', 'Bash']),
    });
    expect(JSON.parse(arg.metadata)).toMatchObject({
      autoGenerated: true,
      patternType: 'refactor',
      sessionCount: 3,
      trigger: 'session-summary',
    });
  });

  it('unknown 模式不建议', async () => {
    initSessionPatternSuggest();
    eventBus.publish('session:summary', { patternType: 'unknown', toolsUsed: ['Edit'] });

    await new Promise((r) => setTimeout(r, 20));
    expect(mockSkillStoreCreate).not.toHaveBeenCalled();
    expect(mockReadStudioEventsSince).not.toHaveBeenCalled();
  });

  it('30d 内不足 3 次不建议（窗口外旧摘要不计数）', async () => {
    mockReadStudioEventsSince.mockResolvedValue([
      summaryEvent('refactor'),
      summaryEvent('refactor'),
      summaryEvent('refactor', 31 * 86_400_000), // 窗口外
    ]);

    initSessionPatternSuggest();
    eventBus.publish('session:summary', { patternType: 'refactor', toolsUsed: ['Edit'] });

    await new Promise((r) => setTimeout(r, 20));
    expect(mockSkillStoreCreate).not.toHaveBeenCalled();
  });

  it('已有同模式 Skill（source 在 proposal/extraction/builtin）→ 不建议', async () => {
    mockReadStudioEventsSince.mockResolvedValue([
      summaryEvent('refactor'), summaryEvent('refactor'), summaryEvent('refactor'),
    ]);
    mockSkillStoreFindFirst.mockReturnValueOnce({ source: 'builtin' });

    initSessionPatternSuggest();
    eventBus.publish('session:summary', { patternType: 'refactor', toolsUsed: ['Edit'] });

    await vi.waitFor(() => {
      expect(mockReadStudioEventsSince).toHaveBeenCalled();
    });
    await new Promise((r) => setTimeout(r, 20));
    expect(mockSkillStoreCreate).not.toHaveBeenCalled();
  });
});
