/**
 * session:summary → 复发模式 Skill 建议（KE-001 Phase 5；#687 依赖倒置：
 * 自 events/session-summary-generator 迁入 skills 模块）
 *
 * events 是基础设施层，不 import 业务模块；generateSessionSummary 落盘
 * session:summary 后在进程内 eventBus 发布同名事件（payload = { patternType, toolsUsed }），
 * 本模块订阅接进来：同一 patternType 30d 内出现 ≥3 次且无同模式 Skill → 建 proposal 草稿。
 */

import { eventBus } from '@dommaker/studio-shared';
// #342：窗口读口（尾部倒读 + 窗口外早停），与 session-summary-generator 同口径
import { readStudioEventsSince } from '../../utils/studio-events-tail.js';
import { skillStore } from './skill-store.js';
import { logger } from '@dommaker/studio-shared/node';

/** #342：事件读窗口 30d——session 跨度 ≪ 窗口；建议本就按 30d 过滤 */
const EVENTS_WINDOW_MS = 30 * 86_400_000;

let started = false;

/** 订阅 eventBus 'session:summary'。幂等：重复调用不再注册（bootstrap/bridges.ts 启动装配时调用一次） */
export function initSessionPatternSuggest(): void {
  if (started) return;
  started = true;

  eventBus.subscribe('session:summary', (payload: { patternType?: string; toolsUsed?: string[] }) => {
    const patternType = payload?.patternType;
    if (!patternType || patternType === 'unknown') return;
    // fire-and-forget：建议失败只 log，不反噬摘要生成链路
    void suggestSkillForPattern(patternType, payload.toolsUsed ?? []).catch((err: unknown) => {
      logger.warn('[SessionPatternSuggest] Skill suggestion failed', { patternType, error: String(err) });
    });
  });
  logger.info('[Skills] Session pattern suggest subscribed');
}

/**
 * KE-001 Phase 5: Suggest Skill for recurring patterns.
 * If a patternType appears 3+ times and has no matching Skill, create a proposal.
 */
async function suggestSkillForPattern(patternType: string, toolsUsed: string[]): Promise<void> {
  // Count recent sessions of this pattern type
  // #342：窗口读 30d（与下方 createdAt >= now-30d 过滤同口径）
  const allSummariesEvents: any[] = await readStudioEventsSince({ sinceMs: Date.now() - EVENTS_WINDOW_MS });
  const recentSummaries = allSummariesEvents.filter((e: any) =>
    e.type === 'session:summary' &&
    typeof e.payload === 'string' && e.payload.includes(`"patternType":"${patternType}"`) &&
    new Date(e.createdAt).getTime() >= Date.now() - 30 * 24 * 60 * 60 * 1000
  ).length;

  if (recentSummaries < 3) return; // Not recurring enough

  // Check if a Skill already exists for this pattern
  const byCategory = skillStore.findFirst({ companyId: 'system', category: patternType });
  const byName = skillStore.findFirst({ companyId: 'system', name: { contains: patternType } });
  const existingSource = (byCategory || byName);
  if (existingSource && ['proposal', 'extraction', 'builtin'].includes(existingSource.source)) return; // Already has a Skill

  // Create proposal
  skillStore.create({
    companyId: 'system',
    name: `Pattern: ${patternType}`.slice(0, 100),
    source: 'proposal',
    status: 'draft',
    category: patternType,
    description: `Recurring pattern "${patternType}" detected (${recentSummaries} sessions in 30d). Tools: ${toolsUsed.join(', ')}`,
    tools: JSON.stringify(toolsUsed),
    metadata: JSON.stringify({
      autoGenerated: true,
      patternType,
      sessionCount: recentSummaries,
      trigger: 'session-summary',
    }),
  });

  logger.info('[SessionPatternSuggest] Skill proposal for recurring pattern', { patternType, sessionCount: recentSummaries });
}
